#!/usr/bin/env python3
"""Build the shipped viz page modules and verify generated-file drift.

Reads the authored assets under ``src/agentic_dev_loop/viz/assets/`` and
inlines them into ``src/agentic_dev_loop/viz/page.py`` (the stdlib-only
server imports ``PAGE`` and ``RUNS_PAGE`` from it). The browser-side
``pipeline-layout.js`` is emitted from the normative reference
implementation so the committed copy cannot silently diverge from it.

The runs page inlines the pinned, vendored ECharts bundle (the full build:
the common build's gauge series registers but renders nothing, which left
the key-stat gauges blank). Its SHA256 is checked before emission; the
vendored copy is the ASCII-sanitized form of the upstream artifact
(upstream SHA256
b66b25aeb4df84e33199dc21694014d336d222cbd9deb0e5a7c14bd6aa0d0fd0).

``--check`` compares generated content with the committed files and exits
non-zero on drift instead of writing.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "src" / "agentic_dev_loop" / "viz" / "assets"
PAGE_HTML = ASSETS / "page.html"
STYLES_CSS = ASSETS / "styles.css"
PAGE_JS = ASSETS / "page.js"
LAYOUT_JS = ASSETS / "pipeline-layout.js"
RUNS_HTML = ASSETS / "runs.html"
RUNS_JS = ASSETS / "runs.js"
ECHARTS_JS = ASSETS / "echarts.min.js"
PAGE_PY = ROOT / "src" / "agentic_dev_loop" / "viz" / "page.py"
REFERENCE_LAYOUT = ROOT / "planning-docs" / "design" / "pipeline-layout.js"

STYLE_LINK = '<link rel="stylesheet" href="styles.css">'
LAYOUT_SCRIPT = '<script src="pipeline-layout.js"></script>'
PAGE_SCRIPT = '<script src="page.js"></script>'
ECHARTS_SCRIPT = '<script src="echarts.min.js"></script>'
RUNS_SCRIPT = '<script src="runs.js"></script>'

ECHARTS_SANITIZED_SHA256 = (
    "182157aedac7b25b5ea8f5d2ddb1a3a3eb6c3116492c157156ef6dda86270757")

PAGE_HEADER = '''"""The shipped viz pages.

Generated by ``tools/build_viz_page.py`` from ``viz/assets/*`` - edit the
assets, not this file, and rebuild.
"""

from __future__ import annotations

PAGE = '''


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _inline_style() -> str:
    return "<style>\n" + _read(STYLES_CSS) + "</style>"


def render_page() -> str:
    html = _read(PAGE_HTML)
    # Embed the normative reference implementation when it exists: the
    # emitted assets copy is only refreshed by the same run that writes
    # page.py, so reading it here would embed stale layout content.
    layout_source = (_read(REFERENCE_LAYOUT) if REFERENCE_LAYOUT.exists()
                     else _read(LAYOUT_JS))
    inline_layout = "<script>\n" + layout_source + "</script>"
    inline_page = "<script>\n" + _read(PAGE_JS) + "</script>"
    for marker in (STYLE_LINK, LAYOUT_SCRIPT, PAGE_SCRIPT):
        if html.count(marker) != 1:
            raise SystemExit(f"page.html must contain exactly one {marker!r}")
    page = (html.replace(STYLE_LINK, _inline_style())
                .replace(LAYOUT_SCRIPT, inline_layout)
                .replace(PAGE_SCRIPT, inline_page))
    page.encode("ascii")
    return page


def _verify_echarts() -> None:
    data = ECHARTS_JS.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != ECHARTS_SANITIZED_SHA256:
        raise SystemExit(
            f"{ECHARTS_JS} SHA256 {digest} does not match the pinned "
            f"artifact {ECHARTS_SANITIZED_SHA256}")


def render_runs_page() -> str | None:
    """Emit the runs page; ``None`` when the runs assets are not present."""
    if not (RUNS_HTML.is_file() and RUNS_JS.is_file()
            and ECHARTS_JS.is_file()):
        return None
    _verify_echarts()
    html = _read(RUNS_HTML)
    for marker in (STYLE_LINK, ECHARTS_SCRIPT, RUNS_SCRIPT):
        if html.count(marker) != 1:
            raise SystemExit(f"runs.html must contain exactly one {marker!r}")
    page = (html.replace(STYLE_LINK, _inline_style())
                .replace(ECHARTS_SCRIPT, "<script>\n" + _read(ECHARTS_JS)
                         + "</script>")
                .replace(RUNS_SCRIPT, "<script>\n" + _read(RUNS_JS)
                         + "</script>"))
    page.encode("ascii")
    return page


def render_page_module(page: str, runs_page: str | None = None) -> str:
    body = PAGE_HEADER + json.dumps(page) + "\n"
    body += "\nRUNS_PAGE = " + json.dumps(runs_page) + "\n"
    return body


def render_layout() -> str | None:
    if not REFERENCE_LAYOUT.exists():
        return None
    return _read(REFERENCE_LAYOUT)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail on drift instead of writing")
    args = parser.parse_args(argv)

    page = render_page()
    runs_page = render_runs_page()
    expected = {
        PAGE_PY: render_page_module(page, runs_page),
    }
    reference = render_layout()
    if reference is not None:
        expected[LAYOUT_JS] = reference
    expected[LAYOUT_JS].encode("ascii")

    drift = []
    for path, content in expected.items():
        current = _read(path) if path.exists() else None
        if args.check:
            if current != content:
                drift.append(path)
        elif current != content:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")

    if drift:
        for path in drift:
            print(f"drift: {path.relative_to(ROOT)} is stale", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
