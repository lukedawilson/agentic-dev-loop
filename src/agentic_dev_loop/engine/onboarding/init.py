"""``agentic-dev-loop init``: render a consumer pipeline from a profile.

Detection answers what it can, questions cover the rest, and the renderer
drops optional gates and rewires the on_pass chain so the emitted pipeline
passes ``load_config`` validation by construction.
"""

from __future__ import annotations

import argparse
import importlib.metadata
import sys
import textwrap
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from agentic_dev_loop.core.profiles import (
    Profile,
    ProfileError,
    load_profile,
)

from .recipes import (
    RecipeError,
    bundled_recipe_names,
    load_recipe,
    undeclared_tokens,
)
from .templates import TemplateError, load_template, render_dev_template

__all__ = ["Detection", "InitError", "detect", "run_init"]

KNOWN_LOCKFILES = ("uv.lock", "package-lock.json", "packages.lock.json",
                   "poetry.lock")
DETECTED_SOURCES = {
    "__SOLUTION__": "solutions",
    "__FRONTEND_DIR__": "frontend_dirs",
}
DEFAULT_LLM = {
    "model": "openai/deepseek-v4-pro",
    "base_url": "https://api.deepseek.com",
    "api_key_env": "OPENAI_API_KEY",
}
GENERATED_COMMENT = (
    "# Generated by `agentic-dev-loop init`. Edit freely; re-running init\n"
    "# against an existing agentic-dev-loop/ directory refuses to overwrite.\n"
)


class InitError(ValueError):
    """A loud, actionable init failure."""


@dataclass
class Detection:
    solutions: list[str] = field(default_factory=list)
    frontend_dirs: list[str] = field(default_factory=list)
    lockfiles: list[str] = field(default_factory=list)
    gitignore_lines: list[str] = field(default_factory=list)
    readme: str | None = None
    agents_md: bool = False
    conformance: bool = False


def detect(root: Path) -> Detection:
    root = Path(root)
    solutions = sorted(
        p.relative_to(root).as_posix() for p in root.rglob("*.sln"))
    frontend_dirs = sorted({
        p.parent.relative_to(root).as_posix()
        for p in root.rglob("package.json")
        if "node_modules" not in p.relative_to(root).parts
    })
    lockfiles = sorted({
        p.relative_to(root).as_posix()
        for name in KNOWN_LOCKFILES
        for p in root.rglob(name)
    })
    gitignore = root / ".gitignore"
    lines = (gitignore.read_text(encoding="utf-8").splitlines()
             if gitignore.is_file() else [])
    readme = next(
        (name for name in ("README.md", "README.rst", "README.txt")
         if (root / name).is_file()), None)
    return Detection(
        solutions=solutions,
        frontend_dirs=frontend_dirs,
        lockfiles=lockfiles,
        gitignore_lines=lines,
        readme=readme,
        agents_md=(root / "AGENTS.md").is_file(),
        conformance=(root / "tools" / "run-conformance.sh").is_file(),
    )


def _installed_version() -> str:
    try:
        return importlib.metadata.version("agentic-dev-loop")
    except importlib.metadata.PackageNotFoundError as exc:
        raise InitError(
            "cannot read the installed agentic-dev-loop version; "
            "install the engine with pipx first") from exc


def _prompt(question: str, default: str | None, yes: bool) -> str:
    if yes:
        if default is None:
            raise InitError(f"--yes cannot answer this question: {question}")
        return default
    suffix = f" [{default}]" if default else ""
    answer = input(f"{question}{suffix}: ").strip()
    if not answer:
        if default is None:
            raise InitError(f"a value is required for: {question}")
        return default
    return answer


def _prompt_choice(question: str, candidates: list[str], yes: bool) -> str:
    if yes:
        raise InitError(
            f"--yes cannot choose between {len(candidates)} candidates for "
            f"{question}: " + ", ".join(candidates))
    for index, candidate in enumerate(candidates, start=1):
        print(f"  {index}. {candidate}", file=sys.stderr)
    answer = input(f"{question} [1-{len(candidates)}]: ").strip()
    try:
        choice = int(answer)
    except ValueError as exc:
        raise InitError(f"invalid choice: {answer!r}") from exc
    if not 1 <= choice <= len(candidates):
        raise InitError(f"invalid choice: {answer!r}")
    return candidates[choice - 1]


def _resolve_tokens(recipe: dict, detection: Detection,
                    yes: bool) -> dict[str, str]:
    placeholders = recipe.get("placeholders") or {}
    values: dict[str, str] = {}
    for token, spec in placeholders.items():
        if spec != "DETECTED":
            continue
        source = DETECTED_SOURCES.get(token)
        if source is None:
            raise InitError(f"recipe token {token} has no detection source")
        candidates = getattr(detection, source)
        if len(candidates) == 1:
            values[token] = candidates[0]
        elif len(candidates) > 1:
            values[token] = _prompt_choice(f"choose {token}", candidates, yes)
        else:
            values[token] = _prompt(
                f"{token} (nothing detected; enter a value)", None, yes)

    for _ in range(len(placeholders) + 1):
        changed = False
        for token, spec in placeholders.items():
            if token in values:
                continue
            expanded = str(spec)
            for other, other_value in values.items():
                expanded = expanded.replace(other, other_value)
            if expanded != str(spec) or not any(
                    t in expanded for t in placeholders):
                values[token] = expanded
                changed = True
        if not changed:
            break
    unresolved = {t for t, v in values.items()
                  if any(other in v for other in placeholders)}
    if unresolved:
        raise InitError(
            "unresolved recipe tokens: " + ", ".join(sorted(unresolved)))
    return values


def _substitute(node, values: dict[str, str]):
    if isinstance(node, dict):
        return {key: _substitute(value, values) for key, value in node.items()}
    if isinstance(node, list):
        return [_substitute(item, values) for item in node]
    if isinstance(node, str):
        for token, value in values.items():
            node = node.replace(token, value)
        return node
    return node


def _drop_optional(steps: list[dict], root: Path) -> list[dict]:
    kept: list[dict] = []
    for step in steps:
        optional = step.get("optional")
        if isinstance(optional, dict) and "detect" in optional:
            if not (root / str(optional["detect"])).exists():
                continue
        kept.append(step)
    return kept


def _rewire(steps: list[dict]) -> None:
    for current, following in zip(steps, steps[1:]):
        if current.get("name") == "commit":
            continue
        current["on_pass"] = following["name"]


def _uses_browser_class(steps: list[dict]) -> bool:
    for step in steps:
        egress = step.get("egress")
        if isinstance(egress, dict) and egress.get("class") == "browser":
            return True
    return False


def _prune_brief_includes(steps: list[dict], root: Path) -> None:
    for step in steps:
        brief_inputs = step.get("brief_inputs")
        if not isinstance(brief_inputs, dict):
            continue
        include = brief_inputs.get("include")
        if not isinstance(include, list):
            continue
        kept: list[str] = []
        for spec in include:
            if any(mark in str(spec) for mark in "*?["):
                if any(Path(p).is_file() for p in root.glob(str(spec))):
                    kept.append(spec)
            elif (root / str(spec)).is_file():
                kept.append(spec)
            else:
                print(f"init: skipping missing brief input: {spec}",
                      file=sys.stderr)
        brief_inputs["include"] = kept


def _render(profile: Profile, recipe: dict, detection: Detection,
            root: Path, answers: dict, installed: str) -> tuple[dict, dict]:
    values = _resolve_tokens(recipe, detection, answers["yes"])
    steps = _drop_optional(_substitute(recipe["steps"], values), root)
    _prune_brief_includes(steps, root)
    _rewire(steps)
    for step in steps:
        step.pop("kind", None)
        step.pop("optional", None)

    additional_files = [
        rel for rel in ("../README.md", "../AGENTS.md")
        if _source_exists(root, rel)
    ]
    browser = _uses_browser_class(steps)
    pipeline: dict = {
        "name": answers["name"],
        "profile": answers["profile_ref"],
        "llm": dict(answers["llm"]),
        "max_attempts": 10,
        "agents_dir": "sdk_agents",
        "deps_policy": "locked" if detection.lockfiles else "open",
    }
    if detection.lockfiles:
        pipeline["lockfiles"] = detection.lockfiles
    if additional_files:
        pipeline["additional_files"] = additional_files
    if browser:
        pipeline["caches"] = ["qa/.browsers"]
    if answers["secrets"]:
        pipeline["secrets"] = answers["secrets"]
    pipeline["steps"] = steps
    dev_text = render_dev_template(
        load_template("dev.agent.md"),
        impossible_set=_substitute(recipe.get("dev_impossible_set", []), values),
        sandbox_notes=_sandbox_notes(recipe, values, steps),
    )
    return pipeline, {"dev": dev_text}


def _source_exists(root: Path, pipeline_relative: str) -> bool:
    base = root / "agentic-dev-loop"
    return (base / pipeline_relative).resolve().is_file()


def _sandbox_notes(recipe: dict, values: dict[str, str],
                   steps: list[dict]) -> list[str]:
    notes = list(_substitute(recipe.get("brief_env_facts", []), values))
    dev = next((s for s in steps if s.get("name") == "dev"), {})
    mounts = dev.get("mounts") or []
    modes = ", ".join(sorted({m.get("mode", "ro") for m in mounts})) or "none"
    notes.append(f"your workspace mount for this step is {modes}")
    notes.append("network is off unless this step declares it")
    return notes


def _write(root: Path, profile: Profile, pipeline: dict, texts: dict,
           detection: Detection, installed: str) -> Path:
    out = root / "agentic-dev-loop"
    out.mkdir(parents=True, exist_ok=True)
    pipeline_path = out / "pipeline.yaml"
    pipeline_path.write_text(
        GENERATED_COMMENT + yaml.safe_dump(
            pipeline, sort_keys=False, default_flow_style=False),
        encoding="utf-8")

    agents = out / "sdk_agents"
    agents.mkdir(parents=True, exist_ok=True)
    (agents / "dev.agent.md").write_text(texts["dev"], encoding="utf-8")
    for name in ("qa", "review"):
        (agents / f"{name}.agent.md").write_text(
            load_template(f"{name}.agent.md"), encoding="utf-8")

    trigger = root / "trigger-agentic-dev-loop.sh"
    trigger.write_text(load_template("trigger-agentic-dev-loop.sh"),
                       encoding="utf-8")
    trigger.chmod(0o755)

    (out / ".engine-version").write_text(installed + "\n", encoding="utf-8")

    for premise in profile.premise_files:
        path = root / premise.path
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(premise.content, encoding="utf-8")

    additions = list(profile.gitignore_additions)
    if _uses_browser_class(pipeline["steps"]):
        additions.append("qa/.browsers/")
    _append_gitignore(root / ".gitignore", additions)

    env_template = root / "agentic-dev-loop.env.example"
    if not env_template.exists():
        env_template.write_text(load_template("env.example"), encoding="utf-8")
    return pipeline_path


def _append_gitignore(path: Path, additions: list[str]) -> None:
    existing: list[str] = []
    if path.is_file():
        existing = path.read_text(encoding="utf-8").splitlines()
    missing = [entry for entry in additions if entry not in existing]
    if not missing:
        return
    lines = existing + missing
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _answers(root: Path, profile_ref: str, yes: bool) -> dict:
    name = _prompt("pipeline name", root.name or "repo", yes)
    llm = {
        "model": _prompt("LLM model", DEFAULT_LLM["model"], yes),
        "base_url": _prompt("LLM base_url", DEFAULT_LLM["base_url"], yes),
        "api_key_env": _prompt("LLM api_key_env", DEFAULT_LLM["api_key_env"],
                               yes),
    }
    secrets: dict[str, dict] = {}
    if not yes:
        raw_names = input(
            "secret ref names (comma-separated, blank for none): ").strip()
        for ref in (part.strip() for part in raw_names.split(",")):
            if not ref:
                continue
            secrets[ref] = {"from": "env", "key": ref.upper().replace("-", "_")}
    return {
        "yes": yes,
        "name": name,
        "llm": llm,
        "secrets": secrets,
        "profile_ref": profile_ref,
    }


def run_init(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        prog="agentic-dev-loop init",
        description="Write agentic-dev-loop pipeline, agent, and trigger "
                    "files for this repo.")
    parser.add_argument("--profile", default="python",
                        help="bundled profile name or path (default: python)")
    parser.add_argument("--recipe", default=None,
                        help="recipe name (default: the profile name when it "
                             "is bundled, else python)")
    parser.add_argument("--yes", action="store_true",
                        help="accept defaults without prompting")
    parser.add_argument("--dir", default=".",
                        help="repo root to write into (default: .)")
    args = parser.parse_args(argv)
    root = Path(args.dir).resolve()
    try:
        pipeline_path = root / "agentic-dev-loop" / "pipeline.yaml"
        if pipeline_path.exists():
            raise InitError(
                f"{pipeline_path} already exists; init never overwrites an "
                "existing agentic-dev-loop/ directory. Edit that pipeline by "
                "hand, or move the directory aside and re-run init.")
        installed = _installed_version()
        profile = load_profile(args.profile, installed)
        bundled = bundled_recipe_names()
        recipe_name = args.recipe
        if recipe_name is None:
            recipe_name = profile.name if profile.name in bundled else "python"
        try:
            recipe = load_recipe(recipe_name)
        except RecipeError as exc:
            raise InitError(str(exc)) from exc
        missing_tokens = undeclared_tokens(recipe)
        if missing_tokens:
            raise InitError(
                "recipe declares no value for token(s): "
                + ", ".join(sorted(missing_tokens)))
        detection = detect(root)
        answers = _answers(root, args.profile, args.yes)
        pipeline, texts = _render(profile, recipe, detection, root, answers,
                                  installed)
        written = _write(root, profile, pipeline, texts, detection, installed)
    except (InitError, ProfileError, RecipeError, TemplateError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    _print_next_steps(written)
    return 0


def _print_next_steps(pipeline_path: Path) -> None:
    print(textwrap.dedent(f"""\
        Wrote {pipeline_path}
        Next steps:
          1. Export the LLM key named by api_key_env in the host environment
             (or set AGENTIC_DEV_LOOP_ENV_FILE to a host env file).
          2. Review agentic-dev-loop/pipeline.yaml and the agent files under
             agentic-dev-loop/sdk_agents/.
          3. Validate: agentic-dev-loop agentic-dev-loop/pipeline.yaml --dry-run
          4. Run: ./trigger-agentic-dev-loop.sh --plan <path> (or --aidlc-unit,
             or --resume).
        """))
